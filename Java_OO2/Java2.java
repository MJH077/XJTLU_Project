public class Java2{
    public static void main(String[] args){
        System.out.println("HelloWorld!");

        /* 程序解释：
      public 公开的
      class 定义一个类
      HelloWorld 一个类名
      public class HelloWorld 表示定义一个公开的类，成为“类体”，除了声明变量以外，类体当中不允许直接编写java语句
      static 静态的
      void 空的
      main 主方法名
      (String[] args)是一个main方法的形式参数列表
      public static void main(String[] args) 表示定义一个公开静态的主方法，是一个程序的主方法和入口
      System.out.println("HelloWorld") 是一个java语句，作用是向控制台输出一段消息

    符号标记：
       1.java以;终止，分号必须为半角分号
       2.双引号必须为半角双引号
       3.java中所有的字符串都要用双引号括起来
 */

    }
}

